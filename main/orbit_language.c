void orbit_language_set(unsigned language) {
    current_language = language < ORBIT_LANGUAGE_COUNT ? language : ORBIT_ZH_CN;
}
unsigned orbit_language_get(void) { return current_language; }
const char *orbit_tr(const char *source) {
    if (!current_language || !source) return source;
    for (size_t i = 0; i < sizeof(words)/sizeof(words[0]); ++i)
        if (!strcmp(source, words[i][0])) return words[i][current_language];
    return source;
}
